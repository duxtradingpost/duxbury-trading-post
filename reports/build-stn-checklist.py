#!/usr/bin/env python3
"""Rebuild the Josh Allen Stars in the Night checklist on public/in-search-of.html.

    python3 reports/build-stn-checklist.py

Craig, 21 Oct 2026: "add my progress for the stars in the night on the in search of
page". Same layout as the Color Blast set (build-cb-checklist.py), placed below it.
Cards and what is owned live in reports/stars-in-the-night-set.json; this rewrites
the block between the STN-CHECKLIST markers (inserting them after the Color Blast
block the first time). No prices on the website.
"""
import html, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
PAGE = os.path.join(HERE, '..', 'public', 'in-search-of.html')
data = json.load(open(os.path.join(HERE, 'stars-in-the-night-set.json')))

cards = [c for s in data['sets'] for c in s['cards']]
have = sum(c['owned'] for c in cards)
e = html.escape
out = [f'''<section class="cb-set" id="stars-in-the-night-set" aria-labelledby="stn-set-title">
  <div class="container">
    <p class="cb-eyebrow">In Search Of</p>
    <h2 class="section-title" id="stn-set-title">Josh Allen Stars in the Night</h2>
    <p class="section-sub">Every parallel of the 2025 Topps Cosmic Chrome Stars in the Night #STN-12. Have one we still need? <a href="index.html#contact">Get in touch</a>.</p>
    <div class="cb-progress"><span class="cb-count"><b>{have}</b> of {len(cards)} in the collection</span>
      <div class="cb-bar" role="progressbar" aria-label="Stars in the Night progress" aria-valuemin="0" aria-valuemax="{len(cards)}" aria-valuenow="{have}"><i style="width:{have / len(cards) * 100:.1f}%"></i></div></div>''']
for s in data['sets']:
    got = sum(c['owned'] for c in s['cards'])
    out.append(f'    <h3 class="cb-group">{e(s["title"])} <span>{got} / {len(s["cards"])}</span></h3>\n    <ul class="cb-list">')
    for c in s['cards']:
        cls = ' class="is-owned"' if c['owned'] else ''
        mark = '<span class="cb-check" aria-label="In the collection">&#10003;</span>' if c['owned'] else '<span class="cb-check" aria-label="Still needed"></span>'
        num = f' <span class="cb-num">{e(c["number"])}</span>' if c['number'] else ''
        out.append(f'      <li{cls}>{mark}<span class="cb-yr">{e(c["year"])}</span> <span class="cb-name">{e(c["name"])}{num}</span></li>')
    out.append('    </ul>')
out.append('  </div>\n</section>')
block = '<!-- STN-CHECKLIST:START (generated by reports/build-stn-checklist.py) -->\n' + '\n'.join(out) + '\n<!-- STN-CHECKLIST:END -->'

page = open(PAGE).read()
if 'STN-CHECKLIST:START' in page:
    page = re.sub(r'<!-- STN-CHECKLIST:START.*?STN-CHECKLIST:END -->', lambda m: block, page, flags=re.S)
elif '<!-- CB-CHECKLIST:END -->' in page:
    page = page.replace('<!-- CB-CHECKLIST:END -->', '<!-- CB-CHECKLIST:END -->\n\n' + block, 1)
else:
    raise SystemExit('CB-CHECKLIST:END marker missing from ' + PAGE)
open(PAGE, 'w').write(page)
print(f'{have} of {len(cards)} owned; {os.path.basename(PAGE)} updated')
