#!/usr/bin/env python3
"""Rebuild the Josh Allen Downtown / Uptown checklist on public/in-search-of.html.

    python3 reports/build-dtut-checklist.py

Craig, 2 Nov 2026: "collect all the Josh Allen uptown and downtowns in PSA 10s.
Preferably black pandora where available" + "Add that checklist to the site as well".
Same layout as the Color Blast / Stars in the Night sets, placed below Stars in the Night.
Cards and what is owned live in reports/downtown-uptown-set.json; this rewrites the
block between the DTUT-CHECKLIST markers (inserting them after the STN block the first
time). No prices on the website.
"""
import html, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
PAGE = os.path.join(HERE, '..', 'public', 'in-search-of.html')
data = json.load(open(os.path.join(HERE, 'downtown-uptown-set.json')))

cards = [c for s in data['sets'] for c in s['cards']]
have = sum(c['owned'] for c in cards)
e = html.escape
out = [f'''<section class="cb-set" id="downtown-uptown-set" aria-labelledby="dtut-set-title">
  <div class="container">
    <p class="cb-eyebrow">In Search Of</p>
    <h2 class="section-title" id="dtut-set-title">Josh Allen Downtown &amp; Uptown</h2>
    <p class="section-sub">Every Josh Allen Downtown and Uptown in PSA 10, Black Pandora where it exists. Have one we still need? <a href="index.html#contact">Get in touch</a>.</p>
    <div class="cb-progress"><span class="cb-count"><b>{have}</b> of {len(cards)} in the collection</span>
      <div class="cb-bar" role="progressbar" aria-label="Downtown and Uptown progress" aria-valuemin="0" aria-valuemax="{len(cards)}" aria-valuenow="{have}"><i style="width:{have / len(cards) * 100:.1f}%"></i></div></div>''']
for s in data['sets']:
    got = sum(c['owned'] for c in s['cards'])
    out.append(f'    <h3 class="cb-group">{e(s["title"])} <span>{got} / {len(s["cards"])}</span></h3>\n    <ul class="cb-list">')
    for c in s['cards']:
        cls = ' class="is-owned"' if c['owned'] else ''
        mark = '<span class="cb-check" aria-label="In the collection">&#10003;</span>' if c['owned'] else '<span class="cb-check" aria-label="Still needed"></span>'
        num = f' <span class="cb-num">{e(c["number"])}</span>' if c['number'] else ''
        out.append(f'      <li{cls}>{mark}<span class="cb-yr">{e(c["year"])}</span> <span class="cb-name">{e(c["name"])}{num}</span></li>')
    out.append('    </ul>')
out.append('  </div>\n</section>')
block = '<!-- DTUT-CHECKLIST:START (generated by reports/build-dtut-checklist.py) -->\n' + '\n'.join(out) + '\n<!-- DTUT-CHECKLIST:END -->'

page = open(PAGE).read()
if 'DTUT-CHECKLIST:START' in page:
    page = re.sub(r'<!-- DTUT-CHECKLIST:START.*?DTUT-CHECKLIST:END -->', lambda m: block, page, flags=re.S)
elif '<!-- STN-CHECKLIST:END -->' in page:
    page = page.replace('<!-- STN-CHECKLIST:END -->', '<!-- STN-CHECKLIST:END -->\n\n' + block, 1)
else:
    raise SystemExit('STN-CHECKLIST:END marker missing from ' + PAGE)
open(PAGE, 'w').write(page)
print(f'{have} of {len(cards)} owned; {os.path.basename(PAGE)} updated')
